"""Contratos de los repositorios — patrón REPOSITORY.

La lógica de negocio depende de estas interfaces, no de SQL ni de Redis.
Hay dos implementaciones: `postgres.py` / `redis_flota.py` (producción) y
`memoria.py` (pruebas unitarias sin infraestructura).
"""
from datetime import datetime
from typing import Any, Protocol

from ..domain.models import EstadoBus, InfraccionCandidata, Telemetria


class UsuarioRepository(Protocol):
    async def por_email(self, conn, email: str) -> dict | None: ...


class InfraccionRepository(Protocol):
    async def crear(self, conn, c: InfraccionCandidata) -> dict: ...
    async def obtener(self, conn, id: str) -> dict | None: ...
    async def listar(self, conn, *, estado, tipo, bus_id, desde, hasta,
                     limit: int, offset: int) -> tuple[list[dict], int]: ...
    async def cambiar_estado(self, conn, id: str, desde: list[str], hasta: str) -> bool: ...


class ActaRepository(Protocol):
    async def crear(self, conn, *, infraccion_id: str, fiscalizador_id: str, resolucion: str,
                    observaciones: str, sancion: dict | None, evidencia: dict) -> dict: ...
    async def listar(self, conn, limit: int, offset: int) -> list[dict]: ...


class AuditoriaRepository(Protocol):
    async def bloquear(self, conn) -> None: ...
    async def ultimo_hash(self, conn) -> str | None: ...
    async def insertar(self, conn, e: dict) -> dict: ...
    async def listar(self, conn, limit: int, offset: int, accion: str | None) -> tuple[list[dict], int]: ...
    async def recorrer(self, conn, despues_de_id: int, limite: int) -> list[dict]: ...


class TelemetriaRepository(Protocol):
    async def insertar_lote(self, conn, lote: list[Telemetria]) -> None: ...
    async def muestras_alrededor(self, conn, bus_id: str, ts: datetime,
                                 minutos: int, limite: int) -> list[dict]: ...


class UmbralRepository(Protocol):
    async def listar(self, conn) -> list[dict]: ...
    async def actualizar(self, conn, clave: str, valor: float, version: int, actor_id: str) -> dict | None: ...


class CatalogoRepository(Protocol):
    async def rutas(self, conn) -> dict[str, list]: ...
    async def bus_ruta(self, conn) -> dict[str, str]: ...


class ReporteRepository(Protocol):
    async def cumplimiento(self, conn, desde: datetime, hasta: datetime, vmax: float) -> list[dict]: ...
    async def serie_horaria(self, conn, concesionaria_id: int, desde: datetime,
                            hasta: datetime) -> list[dict]: ...


class FlotaRepository(Protocol):
    async def actualizar(self, t: Telemetria) -> bool: ...
    async def snapshot(self, ahora: datetime | None = None) -> list[EstadoBus]: ...


class Cooldown(Protocol):
    async def adquirir(self, clave: str, segundos: int) -> bool: ...


Row = dict[str, Any]
